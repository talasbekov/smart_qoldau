-- Р-27: психолог видит имя и историю встреч клиента.
--
-- display_name — как к человеку обращаться. До этого решения продукт
-- имени НЕ собирал вовсе: анонимность была не «скрыто», а «не спрошено».
-- Поле nullable намеренно: у всех существующих пользователей имени нет и
-- взяться ему неоткуда, спросим при первой заявке.
--
-- expert_visibility_accepted_at — ВРЕМЯ согласия, а не флаг. Нужно уметь
-- ответить, когда и на что человек согласился, и отделить консультации,
-- проведённые ДО согласия: они остаются под кодом клиента, потому что
-- проходили под обещанием анонимности.
ALTER TABLE "users" ADD COLUMN     "display_name" TEXT,
ADD COLUMN     "expert_visibility_accepted_at" TIMESTAMP(3);
