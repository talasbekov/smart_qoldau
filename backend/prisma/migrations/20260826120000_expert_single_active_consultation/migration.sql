-- Эксперт ведёт не больше одной консультации одновременно. Раньше это
-- держалось только на переводе в BUSY, который происходит ПОСЛЕ коммита
-- первого accept: нагрузочный прогон E11 показал, что до этого момента
-- эксперт успевает принять второй оффер и получить вторую активную
-- консультацию — с отдельным холдом денег на каждой.
--
-- Существующий consultations_expert_slot_uq (expert_id, started_at) от
-- этого не защищает: у двух мгновенных консультаций started_at различается
-- на миллисекунды. Он остаётся — он про плановые слоты.
--
-- Перед индексом разбираем то, что старая гонка уже успела наплодить: на
-- боевой базе у эксперта могут висеть две активные консультации, и тогда
-- CREATE UNIQUE INDEX просто уронит миграцию, а вместе с ней и деплой.
-- Оставляем самую свежую (её и ведут на самом деле), остальные закрываем
-- как технический сбой — по смыслу это ровно он: консультация, которой не
-- должно было существовать. Исход TECH_ISSUE означает возврат клиенту и 0 ₸
-- специалисту; незакрытые холды по ним подберёт обычный sweep расчётов.
UPDATE consultations c
SET status = 'COMPLETED',
    outcome = 'TECH_ISSUE',
    ended_at = NOW()
WHERE c.status = 'ACTIVE'
  AND c.id <> (
    SELECT c2.id
    FROM consultations c2
    WHERE c2.expert_id = c.expert_id
      AND c2.status = 'ACTIVE'
    ORDER BY c2.started_at DESC, c2.id DESC
    LIMIT 1
  );

-- Частичный уникальный индекс Prisma не выражает, поэтому сырым SQL.
CREATE UNIQUE INDEX consultations_expert_active_uq
  ON consultations (expert_id)
  WHERE status = 'ACTIVE';
