// Константы плановых консультаций (E6b) — в одном месте, а не
// разбросанные по коду: каждое значение обосновано.

/// Сетка слотов: 50 минут сессии (Р-05) + 10 минут буфера. Без буфера
/// сессия, затянувшаяся на пару минут, механически ломает следующую
/// запись; десять минут — минимальный зазор, не съедающий пропускную
/// способность специалиста.
export const SLOT_MINUTES = 60;
export const SESSION_MINUTES = 50;

/// Горизонт записи. Дальше двух недель расписание перестаёт быть
/// достоверным: специалист ещё не знает своих планов.
export const HORIZON_DAYS = 14;

/// Минимальный отступ от «сейчас»: за час клиент успевает дойти до места,
/// где ему удобно говорить, а специалист — увидеть запись.
export const LEAD_MINUTES = 60;

/// Отмена позже этого срока считается поздней и идёт в счётчик
/// злоупотреблений (Р-17): за два часа специалист ещё может занять слот.
export const LATE_CANCEL_HOURS = 2;

/// Напоминание обеим сторонам (Р-15).
export const REMINDER_MINUTES = 15;

/// Asia/Almaty — UTC+5 круглый год: переход на летнее время в Казахстане
/// отменён, и единая зона зафиксирована в ТЗ §4.4.
export const ALMATY_OFFSET_MINUTES = 300;
