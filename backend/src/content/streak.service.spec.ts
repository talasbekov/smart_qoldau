import { currentStreak, longestStreak, toAlmatyDate } from './streak.service';

function d(iso: string): Date {
  return new Date(`${iso}T09:00:00Z`);
}

describe('Стрик практик', () => {
  it.each([
    [['2026-08-26', '2026-08-25', '2026-08-24'], '2026-08-26', 3],
    // Вчера занимался, сегодня ещё нет — стрик ЖИВ. Он рвётся, когда
    // пропущен целый день, а не в полночь: иначе человек «теряет» стрик,
    // просто не успев зайти с утра.
    [['2026-08-25', '2026-08-24'], '2026-08-26', 2],
    // Пропущено вчера — обнулился.
    [['2026-08-24'], '2026-08-26', 0],
    [[], '2026-08-26', 0],
    // Два раза за один день — один день, а не два.
    [['2026-08-26', '2026-08-26'], '2026-08-26', 1],
  ])('дни %j на дату %s дают стрик %i', (days, today, expected) => {
    expect(currentStreak(days.map(d), d(today))).toBe(expected);
  });

  it('самый длинный стрик считается по всей истории, а не по хвосту', () => {
    const days = [
      '2026-08-01',
      '2026-08-02',
      '2026-08-03',
      '2026-08-04', // четыре подряд
      '2026-08-20',
      '2026-08-21', // и два подряд позже
    ].map(d);
    expect(longestStreak(days)).toBe(4);
  });

  it('дата берётся в часовом поясе Алматы, а не в UTC', () => {
    // 2026-08-25T19:30Z — это уже 26 августа в Алматы (UTC+5). Считать по
    // UTC значит терять людям день практики каждый вечер.
    expect(toAlmatyDate(new Date('2026-08-25T19:30:00Z'))).toBe('2026-08-26');
    expect(toAlmatyDate(new Date('2026-08-25T18:30:00Z'))).toBe('2026-08-25');
  });
});
