// Профили троттлинга. У каждого числа — расчёт: сколько запросов делает
// нормальный пользователь за окно и во сколько раз лимит выше. Значение без
// обоснования — дефект: лимит, подобранный «на глаз», либо не защищает,
// либо ломает живой сценарий.
import { ThrottlerOptions } from '@nestjs/throttler';

const minutes = (n: number) => n * 60_000;
const hours = (n: number) => n * 3_600_000;

// ВАЖНО: все зарегистрированные в модуле профили применяются к маршруту
// ОДНОВРЕМЕННО (@nestjs/throttler v6), поэтому регистрируется ровно один —
// `default`, а каждый маршрут переопределяет его своим профилем через
// `@Throttle({ default: THROTTLE.<профиль> })`. Иначе самый строгий лимит
// из списка молча срабатывал бы на всех эндпоинтах сразу.
export const THROTTLE = {
  /// Вход сотрудника в админку: 5 попыток / 15 минут на email.
  /// Человек ошибается паролем 1–2 раза; 5 — с запасом. Перебор словаря при
  /// этом становится бессмысленным: 20 попыток в час против миллионов
  /// нужных. Ключ — email, а не IP: сотрудники сидят за одним офисным
  /// адресом, и перебор чужого ящика не должен запирать соседа.
  adminLogin: { name: 'default', ttl: minutes(15), limit: 5 },

  /// Запрос SMS-кода: 3 / час на телефон.
  /// Бэкенд уже держит 45 секунд между отправками (`SMS_RATE_LIMITED`) —
  /// этот лимит против медленного слива платного бюджета за сутки: без
  /// него один номер стоит 1920 SMS в сутки.
  smsRequest: { name: 'default', ttl: hours(1), limit: 3 },

  /// Проверка SMS-кода: 10 / 15 минут на телефон.
  /// Код шестизначный, но без лимита перебор всё равно вопрос времени.
  /// Существующий счётчик попыток в `SmsCode` этим не заменяется, а
  /// дополняется: тот считает попытки на код, этот — на номер.
  smsVerify: { name: 'default', ttl: minutes(15), limit: 10 },

  /// Создание заявки: 10 / час на пользователя.
  /// Нормальный клиент создаёт 1–2 заявки за сессию. Кнопка «Попробовать
  /// снова» на экране «нет специалистов» позволяет крутить их без предела,
  /// а каждая заявка тянет платные SMS экспертам.
  createRequest: { name: 'default', ttl: hours(1), limit: 10 },

  /// Попытка оплаты картой: 10 / час на пользователя.
  /// Эндпоинты оплаты консультации и подписки идут к эквайеру с картой,
  /// которую выбрал пользователь, — это классический вектор перебора
  /// краденых карт: привязал, попробовал списать, посмотрел на ответ
  /// банка, повторил. Живому клиенту хватает одной-двух попыток плюс
  /// пересчёт после отказа; 10 в час оставляет запас человеку и делает
  /// перебор бессмысленным.
  paymentAttempt: { name: 'default', ttl: hours(1), limit: 10 },

  /// Создание обращения в поддержку: 5 / час.
  /// Эндпоинт принимает 4200 символов и доступен без аутентификации (форма
  /// поддержки лендинга E10 сядет ровно на него). Живому человеку хватает
  /// одного обращения; 5 — запас на «дописал, отправил ещё раз».
  createTicket: { name: 'default', ttl: hours(1), limit: 5 },
} as const satisfies Record<string, ThrottlerOptions & { name: string }>;

/// Единственный профиль, регистрируемый в модуле. Значения здесь —
/// страховочные: любой маршрут, к которому прикреплён guard, обязан задать
/// свой профиль через `@Throttle`, а этот срабатывает, только если про это
/// забыли (60 запросов в минуту — заведомо выше любого живого сценария).
export const THROTTLE_PROFILES: ThrottlerOptions[] = [
  { name: 'default', ttl: 60_000, limit: 60 },
];
