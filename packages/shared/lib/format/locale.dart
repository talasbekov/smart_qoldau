/// Перевод локали Flutter/ICU в код локали, который понимает бэкенд.
library;

import 'dart:ui' show Locale;

/// Переводит [locale] в код локали, ожидаемый бэкендом:
/// казахский (`kk` в терминах Flutter/ICU) → `'kz'`, всё остальное
/// (в первую очередь `ru`) → `'ru'`.
///
/// Единственное место в кодовой базе, где происходит этот перевод — Flutter
/// именует казахский код локали `kk` (ISO 639-1), бэкенд же ожидает `kz`.
/// Строку `'kk'` в API отправлять нельзя никогда — только через эту функцию.
String localeToApi(Locale locale) {
  return locale.languageCode == 'kk' ? 'kz' : 'ru';
}
